"""Render the fonts and the wordmark of the screen into 4-bit alpha atlases, as C headers in src/ui/.

The atlases hold ASCII 32 to 126, the ellipsis as 127 and the degree sign as 128. The hero size holds only the digits
and + , - . /, to save flash.

Run it from the folder screen/:
    uv run --with pillow --with numpy python tools/make_fonts.py

Each glyph is cut to its ink box and stored as a stream of 4-bit alpha values, two pixels in a byte.
In the sizes for numbers, the digits get one shared advance (the widest digit), with each digit centred
in its cell, so numbers keep their width when they change. Inter has true tabular figures, but Pillow without libraqm cannot
select them, so the generator makes the cells itself.
"""

from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
SCREEN = HERE.parent
FONTS = SCREEN / "fonts"
OUT = SCREEN / "src" / "ui"
BOREL = SCREEN.parent / "enclosure" / "fonts" / "Borel-Regular.ttf"

ASCII = "".join(chr(c) for c in range(32, 129))  # 127 holds the ellipsis, 128 the degree sign
EXTRA = {"\x7f": "\u2026", "\x80": "\u00b0"}
HERO = "".join(chr(c) for c in range(ord("+"), ord("9") + 1))  # + , - . / and the digits

# name, file, pixel size, characters, tabular digits. The sizes for numbers that change get tabular digits;
# the text sizes keep the natural digits, so a time such as "21:00" in a sentence has no gaps.
SETS = [
    ("kInter13M", "Inter-Medium.ttf", 13, ASCII, False),
    ("kInter15R", "Inter-Regular.ttf", 15, ASCII, False),
    ("kInter15M", "Inter-Medium.ttf", 15, ASCII, False),
    ("kInter20S", "Inter-SemiBold.ttf", 20, ASCII, True),
    ("kInter28S", "Inter-SemiBold.ttf", 28, ASCII, True),
    ("kInter60M", "Inter-Medium.ttf", 60, HERO, True),
]


def pack(alpha: np.ndarray) -> list[int]:
    """8-bit alpha to 4-bit values, two in a byte, the first pixel in the high half."""
    q = np.clip(np.round(alpha.astype(np.float32) / 17.0), 0, 15).astype(np.uint8).ravel()
    if len(q) % 2:
        q = np.append(q, 0)
    return list((q[0::2] << 4) | q[1::2])


def glyph(font: ImageFont.FreeTypeFont, ch: str):
    ch = EXTRA.get(ch, ch)
    x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
    w, h = max(0, x1 - x0), max(0, y1 - y0)
    if w == 0 or h == 0 or ch == " ":
        return 0, 0, 0, 0, np.zeros((0, 0), np.uint8)
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
    return w, h, x0, y0, np.array(img)


def c_bytes(data: list[int]) -> str:
    rows = [", ".join(f"0x{b:02X}" for b in data[i:i + 20]) for i in range(0, len(data), 20)]
    return ",\n  ".join(rows)


def make_font(name: str, file: str, size: int, chars: str, tabular: bool) -> int:
    font = ImageFont.truetype(str(FONTS / file), size)
    first, last = ord(chars[0]), ord(chars[-1])
    digit_adv = max(round(font.getlength(d)) for d in "0123456789")
    bits: list[int] = []
    glyphs = []
    for code in range(first, last + 1):
        ch = chr(code)
        if ch not in chars:
            glyphs.append((len(bits), 0, 0, 0, 0, 0))
            continue
        w, h, dx, dy, alpha = glyph(font, ch)
        adv = round(font.getlength(EXTRA.get(ch, ch)))
        if tabular and ch.isdigit():  # a tabular cell: the widest advance, the digit in its centre
            dx += round((digit_adv - adv) / 2)
            adv = digit_adv
        glyphs.append((len(bits), w, h, dx, dy, adv))
        if w and h:
            bits += pack(alpha)
    ascent, descent = font.getmetrics()
    cap = -font.getbbox("H", anchor="ls")[1]
    xh = -font.getbbox("x", anchor="ls")[1]
    body = ",\n  ".join(f"{{{o}, {w}, {h}, {dx}, {dy}, {a}}}" for o, w, h, dx, dy, a in glyphs)
    text = f"""// Generated by tools/make_fonts.py from fonts/{file} at {size} px. Do not edit.
// Inter, Copyright 2016 The Inter Project Authors, SIL Open Font License 1.1.
#pragma once
#include "font.h"
static const uint8_t {name}_bits[] = {{
  {c_bytes(bits)}
}};
static const ui::Glyph {name}_glyphs[] = {{
  {body}
}};
const ui::Font ui::{name} = {{{name}_bits, {name}_glyphs, {first}, {last}, {size}, {ascent}, {descent}, {cap}, {xh}}};
"""
    (OUT / f"font_{name[1:].lower()}.h").write_text(text)
    return len(bits) + len(glyphs) * 8


def make_wordmark(name: str, height: int) -> int:
    """The name "mise" in Borel, cut to its ink and scaled so the ink is the given height."""
    size = height
    for _ in range(40):
        font = ImageFont.truetype(str(BOREL), size)
        x0, y0, x1, y1 = font.getbbox("mise", anchor="ls")
        if y1 - y0 <= height:
            break
        size -= 1
    w, h = x1 - x0, y1 - y0
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((-x0, -y0), "mise", font=font, fill=255, anchor="ls")
    alpha = np.array(img)
    bits = pack(alpha)
    text = f"""// Generated by tools/make_fonts.py: the name "mise" in Borel ({size} px), as 4-bit alpha. Do not edit.
// Borel, Copyright 2023 The Borel Project Authors, SIL Open Font License 1.1.
#pragma once
#include "font.h"
static const uint8_t {name}_bits[] = {{
  {c_bytes(bits)}
}};
const ui::Alpha4 ui::{name} = {{{name}_bits, {w}, {h}, {-y0}}};
"""
    (OUT / f"wordmark_{name[9:].lower()}.h").write_text(text)
    return len(bits)


def main() -> None:
    total = 0
    for name, file, size, chars, tabular in SETS:
        n = make_font(name, file, size, chars, tabular)
        total += n
        print(f"{name:12} {n:7} bytes")
    for name, height in (("kWordmarkSmall", 26), ("kWordmarkLarge", 64)):
        n = make_wordmark(name, height)
        total += n
        print(f"{name:12} {n:7} bytes")
    print(f"total {total} bytes")


if __name__ == "__main__":
    main()
